"""Freeze native BASIC horizontal metrics for the exact bundled DejaVu fonts.

Outline units + sparse hinted-bound corrections cover Latin U+0020..U+024F,
regular/bold, and every supported integer font size (1..16384). This data avoids
using platform-dependent Canvas ink bounds for cartographic layout.
"""
from pathlib import Path
import hashlib
import json
import math
from PIL import ImageFont, features
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
assert features.version('freetype2') == '2.14.3', 'Reference requires pinned FreeType 2.14.3'
first, count, max_size = 32, 560, 16384
records = []
for filename in ('DejaVuSans.ttf', 'DejaVuSans-Bold.ttf'):
    path = root / 'assets/fonts' / filename
    font = TTFont(path)
    cmap, hm, glyf = font.getBestCmap(), font['hmtx'].metrics, font['glyf']
    em = font['head'].unitsPerEm
    names = [cmap.get(code, '.notdef') for code in range(first, first + count)]
    glyphs = []
    for name in names:
        g = glyf[name]
        glyphs.extend([hm[name][0], getattr(g, 'xMin', 0), getattr(g, 'xMax', 0)])
    kern = {}
    native_kern = font['kern'].kernTables[0].kernTable
    for i, a in enumerate(names):
        for j, b in enumerate(names):
            value = native_kern.get((a, b), 0)
            if value: kern[i * count + j] = value
    bounds = {}
    for size in range(1, max_size + 1):
        face = ImageFont.truetype(path, size, layout_engine=ImageFont.Layout.BASIC)
        for i in range(count):
            advance, xmin, xmax = glyphs[i * 3:i * 3 + 3]
            adv = math.floor((math.floor(advance * size * 64 / em + .5) + 32) / 64)
            left, right = min(0, math.floor(xmin * size / em)), max(adv, math.ceil(xmax * size / em))
            actual = face.getbbox(chr(first + i))
            delta = [actual[0] - left, actual[2] - right]
            if any(delta): bounds[size * count + i] = delta
        if size % 4096 == 0: print(filename, size, 'sizes recorded', flush=True)
    records.append({'unitsPerEm':em,'ascent':font['hhea'].ascent,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'glyphs':glyphs,'kern':kern,'bounds':bounds})
source = '// Generated by scripts/generate-w20-font-metrics.py; do not edit.\n'
source += '// Source: DejaVu 2.37 package bytes, Pillow BASIC / FreeType 2.14.3.\n'
source += 'export interface NativeFontMetrics { unitsPerEm: number; ascent: number; sha256: string; glyphs: number[]; kern: Record<number, number>; bounds: Record<number, [number, number]> }\n'
for name, record in zip(('REGULAR_METRICS', 'BOLD_METRICS'), records):
    source += 'export const ' + name + ': NativeFontMetrics = ' + json.dumps(record, separators=(',', ':')) + ';\n'
(root / 'src-ts/cartography-font-metrics.ts').write_text(source,encoding='utf-8',newline='\n')
print('Recorded native horizontal font metrics:', len(source), 'bytes',flush=True)
