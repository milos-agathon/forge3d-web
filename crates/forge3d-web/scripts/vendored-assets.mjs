import './verify-w13-assets.mjs';
import './verify-w14-assets.mjs';
import './verify-w20-assets.mjs';
import './prepare-laz-assets.mjs';
import './prepare-basis-csp.mjs';
import {build} from 'vite';
import {createRequire} from 'node:module';
import {readFileSync,existsSync,unlinkSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {VendoredAssembly} from './vendored-assembly.mjs';

export async function assembleVendoredAssets(root) {
 const lock=JSON.parse(readFileSync(join(root,'../../docs/parity/dependency-lock.json'),'utf8'));
 const npmLock=JSON.parse(readFileSync(join(root,'package-lock.json'),'utf8'));
 const assembly=new VendoredAssembly({root,lock,npmLock});
 const script=(from,to)=>({from,to:'dist/vendor/'+to,script:true});
 const license=(from,to)=>({from,to:'dist/vendor/'+to});
 for(const [id,files,imports] of [
  ['noble-ed25519',[script('index.js','noble-ed25519.js'),license('LICENSE','noble-ed25519.LICENSE')],{'@noble/ed25519':'dist/vendor/noble-ed25519.js'}],
  ['noble-hashes',[...['sha2.js','_md.js','_u64.js','utils.js'].map(name=>script(name,'noble-hashes/'+name)),license('LICENSE','noble-hashes/LICENSE')],{'@noble/hashes/sha2.js':'dist/vendor/noble-hashes/sha2.js'}],
  ['pdf-lib',[script('dist/pdf-lib.esm.min.js','pdf-lib.js'),license('LICENSE.md','pdf-lib.LICENSE')],{'pdf-lib':'dist/vendor/pdf-lib.js'}],
  ['fflate',[script('esm/browser.js','fflate.js'),license('LICENSE','fflate.LICENSE')],{'fflate':'dist/vendor/fflate.js'}],
  ['ktx-parse',[script('dist/ktx-parse.modern.js','ktx-parse.js'),license('LICENSE','ktx-parse.LICENSE')],{'ktx-parse':'dist/vendor/ktx-parse.js'}],
  ['mediabunny',[{from:'dist/bundles/mediabunny.min.mjs',to:'dist/vendor/mediabunny.js'},license('LICENSE','mediabunny.LICENSE')],{'mediabunny':'dist/vendor/mediabunny.js'}],
 ]) assembly.dependency(id,{files,imports});
 assembly.dependency('geotiff',{files:[script('dist-browser/geotiff.js','geotiff.umd.js'),license('LICENSE','geotiff.LICENSE')],imports:{geotiff:'dist/vendor/geotiff.js'},emit:emit=>{
emit("dist/vendor/geotiff.js",
  `${[
    "// Generated by scripts/prepare-dist.mjs -- do not edit.",
    "// ESM wrapper over the vendored geotiff@3.0.5 UMD bundle.",
    'import "./geotiff.umd.js";',
    // The namespace binding must not be named `GeoTIFF`: the destructured
    // `GeoTIFF` class export below would redeclare it (a SyntaxError).
    "const geotiff = globalThis.GeoTIFF;",
    "if (geotiff === undefined) {",
    '  throw new Error("vendored geotiff.umd.js did not populate globalThis.GeoTIFF");',
    "}",
    "export default geotiff;",
    "export const {",
    "  BaseClient,",
    "  BaseDecoder,",
    "  BaseResponse,",
    "  GeoTIFF,",
    "  GeoTIFFImage,",
    "  ImageFileDirectory,",
    "  MultiGeoTIFF,",
    "  Pool,",
    "  addDecoder,",
    "  fromArrayBuffer,",
    "  fromBlob,",
    "  fromCustomClient,",
    "  fromFile,",
    "  fromUrl,",
    "  fromUrls,",
    "  getDecoder,",
    "  globals,",
    "  registerTag,",
    "  rgb,",
    "  setLogger,",
    "  writeArrayBuffer,",
    "} = geotiff;",
    "",
  ].join("\n")}`,
);
 }});
 const vendor=join(root,'dist/vendor');
 for(const file of ['fontkit.umd.js','fontkit-entry.js','fontkit-entry.d.ts'])if(existsSync(join(vendor,file)))unlinkSync(join(vendor,file));
 const fontkitRoot=assembly.dependency('pdf-lib-fontkit',{imports:{'./vendor/fontkit-entry.js':'dist/vendor/fontkit.js'}});
 const pakoRoot=dirname(createRequire(join(fontkitRoot,'package.json')).resolve('pako/package.json'));
 for(const [name,dependencyRoot,key] of [['pako',pakoRoot,'node_modules/@pdf-lib/fontkit/node_modules/pako'],['regenerator-runtime',join(root,'node_modules/regenerator-runtime'),'node_modules/regenerator-runtime']]) {
  const pinned=npmLock.packages[key]??npmLock.packages['node_modules/'+name];
  if(!pinned?.integrity||JSON.parse(readFileSync(join(dependencyRoot,'package.json'),'utf8')).version!==pinned.version)throw Error(`Fontkit transitive lock mismatch: ${name}`);
  assembly.emit(`dist/vendor/${name}.LICENSE`,`${name}@${pinned.version}`,readFileSync(join(dependencyRoot,'LICENSE')));
 }
 await build({configFile:false,publicDir:false,logLevel:'error',build:{lib:{entry:join(root,'src-ts/vendor/fontkit-entry.ts'),formats:['es'],fileName:()=> 'fontkit.js'},outDir:vendor,emptyOutDir:false,minify:true}});
 const fontkit=assembly.record('pdf-lib-fontkit');
 assembly.retain(`${fontkit.package}@${fontkit.version}`,['dist/vendor/fontkit.js']);
 assembly.emit('dist/vendor/fontkit.LICENSE',`${fontkit.package}@${fontkit.version}`,readFileSync(join(root,'assets/licenses/fontkit.LICENSE')));
 for(const [id,paths] of [
  ['laz-perf',['laz-perf.js','laz-perf.wasm','laz-perf.LICENSE'].map(f=>'assets/laz/'+f)],
  ['proj-wasm',['dist/crs-worker.js',...['proj-emscripten.js','proj-emscripten.wasm','proj.db','proj.ini','us_noaa_conus.tif','LICENSE','PROJ-COPYING','GRID-LICENSE.txt'].map(f=>'assets/proj/'+f)]],
  ['basis-universal',['basis_transcoder.js','basis_transcoder.csp.js','basis_transcoder.wasm'].map(f=>'assets/basis/'+f)],
  ['harfbuzzjs',['index.mjs','harfbuzz.js','harfbuzz.wasm','LICENSE'].map(f=>'assets/harfbuzz/'+f)],
 ]) assembly.retainDependency(id,paths);
 assembly.retain('dejavu-fonts@2.37',['dist/cartography-font-metrics.js',...['DejaVuSans.ttf','DejaVuSans-Bold.ttf','DejaVu-LICENSE'].map(f=>'assets/fonts/'+f)]);
 assembly.retain('noto-fonts@ffebf8c1ee449e544955a7e813c54f9b73848eac',[...['NotoSans','NotoSansArabic','NotoSansDevanagari'].map(f=>'assets/fonts/'+f+'-Regular.ttf'),'assets/fonts/OFL.txt']);
 assembly.retain('native@1f4084af428dc699bdcd108b029736cb73903926',['mini_dem.npy','sample_boundaries.geojson'].map(f=>'assets/datasets/'+f));
 return assembly.finish();
}
