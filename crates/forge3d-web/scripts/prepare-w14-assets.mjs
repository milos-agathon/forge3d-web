import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { gunzipSync } from "node:zlib";
const root = new URL("../", import.meta.url);
const upstream = new URL("node_modules/proj-wasm/", root);
const destination = new URL("assets/proj/", root);
mkdirSync(destination, { recursive: true });
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
const get = async (url) => {
  const response = await fetch(url);
  if (!response.ok) throw Error("Asset HTTP " + response.status);
  return Buffer.from(await response.arrayBuffer());
};
if (
  JSON.parse(readFileSync(new URL("package.json", upstream))).version !==
  "0.1.0-alpha9"
)
  throw Error("PROJ version mismatch");
const lock = JSON.parse(
  readFileSync(new URL("../../docs/parity/dependency-lock.json", root)),
);
const source = lock.assets.find((a) => a.id === "proj-wasm");
const archive = await get(source.source.uri);
if (sha(archive) !== source.source.sha256)
  throw Error("PROJ tarball digest mismatch");
// Read regular files directly from the verified archive; never execute tarball code.
const tar = gunzipSync(archive),
  members = new Map();
for (let offset = 0; offset + 512 <= tar.length; ) {
  const header = tar.subarray(offset, offset + 512);
  if (header.every((b) => b === 0)) break;
  const name = header.subarray(0, 100).toString().replace(/\0.*$/s, "");
  const size = parseInt(
    header.subarray(124, 136).toString().replace(/\0.*$/s, "").trim(),
    8,
  );
  if (
    !Number.isSafeInteger(size) ||
    size < 0 ||
    offset + 512 + size > tar.length
  )
    throw Error("Invalid verified tar archive");
  if (header[156] === 0 || header[156] === 48)
    members.set(name, tar.subarray(offset + 512, offset + 512 + size));
  offset += 512 + Math.ceil(size / 512) * 512;
}
const assets = [],
  notices = [];
for (const file of [
  "proj-emscripten.js",
  "proj-emscripten.wasm",
  "proj.db",
  "proj.ini",
  "LICENSE",
]) {
  const path = file === "LICENSE" ? file : "dist/" + file;
  const expected = members.get("package/" + path),
    installed = readFileSync(new URL(path, upstream));
  if (!expected || !installed.equals(expected))
    throw Error("Installed PROJ differs from locked archive: " + file);
  writeFileSync(new URL(file, destination), expected);
  (file === "LICENSE" ? notices : assets).push({
    name: file,
    sha256: sha(expected),
    byteLength: expected.length,
  });
}
const gridUrl = "https://cdn.proj.org/us_noaa_conus.tif";
const grid = await get(gridUrl);
const gridSha =
  "44611d823c48e5347500ee6afe40ff33d2b88cf817bf59f705ed4a4c3bd687d7";
if (sha(grid) !== gridSha || grid.length !== 173029)
  throw Error(
    "Versioned NOAA conus grid changed; an ADR and new fixture version are required",
  );
writeFileSync(new URL("us_noaa_conus.tif", destination), grid);
const gridEntry = {
  name: "us_noaa_conus.tif",
  sha256: gridSha,
  byteLength: grid.length,
  version: "proj-data-conus-v1",
  source: gridUrl,
  license: "Public domain (NOAA/NGS)",
  licenseSource:
    "https://github.com/OSGeo/PROJ-data/blob/1.24.0/us_noaa/us_noaa_README.txt",
};
for (const [name, url] of [
  [
    "PROJ-COPYING",
    "https://raw.githubusercontent.com/OSGeo/PROJ/9.8.1/COPYING",
  ],
  [
    "GRID-LICENSE.txt",
    "https://raw.githubusercontent.com/OSGeo/PROJ-data/1.24.0/us_noaa/us_noaa_README.txt",
  ],
]) {
  const bytes = await get(url);
  writeFileSync(new URL(name, destination), bytes);
  notices.push({
    name,
    source: url,
    sha256: sha(bytes),
    byteLength: bytes.length,
  });
}
const manifest = {
  schemaVersion: 1,
  package: "proj-wasm",
  version: "0.1.0-alpha9",
  tarballSha256: source.source.sha256,
  adapter:
    "Direct exported PROJ C API on the unmodified pinned Emscripten module in a Forge3D worker; network disabled.",
  assets,
  grids: [gridEntry],
  notices,
};
writeFileSync(
  new URL("provenance.json", destination),
  JSON.stringify(manifest, null, 2) + "\n",
);
writeFileSync(
  new URL("src-ts/proj-assets.ts", root),
  "// Generated by scripts/prepare-w14-assets.mjs.\nexport const PROJ_ASSETS = " +
    JSON.stringify(manifest, null, 2) +
    " as const;\n",
);
console.log("Pinned archive bytes, PROJ and versioned grid assets prepared");
